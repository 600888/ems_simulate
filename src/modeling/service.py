    @staticmethod
    def _normalize_legacy_fcda_names(document: ModelDocument) -> None:
        """Repair names generated by the old ``GGIO.1.DO..FC`` formatter."""

        for siblings in document.by_parent.values():
            fcda_nodes = [node for node in siblings if node.kind == "FCDA"]
            if not fcda_nodes:
                continue
            used_names = {
                node.name
                for node in fcda_nodes
                if not re.fullmatch(
                    re.escape(
                        ".".join(
                            str(node.attributes.get(key, "")) for key in ("lnClass", "lnInst", "doName", "daName", "fc")
                        ).strip(".")
                    )
                    + r"(?:_\d+)?",
                    node.name,
                )
            }
            for node in fcda_nodes:
                legacy_name = ".".join(
                    str(node.attributes.get(key, "")) for key in ("lnClass", "lnInst", "doName", "daName", "fc")
                ).strip(".")
                if not legacy_name or not re.fullmatch(
                    re.escape(legacy_name) + r"(?:_\d+)?",
                    node.name,
                ):
                    continue
                base = fcda_reference_name(node.attributes) or "FCDA"
                candidate = base
                suffix = 2
                while candidate in used_names:
                    candidate = f"{base}_{suffix}"
                    suffix += 1
                node.name = candidate
                used_names.add(candidate)

    @staticmethod
    def _materialize_inherited_instance_attributes(document: ModelDocument) -> None:
        """Upgrade older imported documents with effective q/t DOI children."""

        ln_types = {
            str(node.attributes.get("id") or node.name): node for node in document.nodes if node.kind == "LNODE_TYPE"
        }
        do_types = {
            str(node.attributes.get("id") or node.name): node for node in document.nodes if node.kind == "DO_TYPE"
        }
        for logical_node in list(document.nodes):
            if logical_node.kind not in ("LN0", "LN"):
                continue
            ln_type = ln_types.get(str(logical_node.attributes.get("lnType") or ""))
            if ln_type is None:
                continue
            do_definitions = {child.name: child for child in document.children(ln_type.id) if child.kind == "DO_DEF"}
            for doi in (child for child in document.children(logical_node.id) if child.kind == "DOI"):
                do_definition = do_definitions.get(doi.name)
                if do_definition is None:
                    continue
                type_id = str(do_definition.attributes.get("type") or "")
                do_type = do_types.get(type_id)
                if do_type is None:
                    continue
                definitions = {child.name: child for child in document.children(do_type.id) if child.kind == "DA_DEF"}
                existing = {child.name for child in document.children(doi.id) if child.kind == "DAI"}
                next_order = (
                    max(
                        (child.sort_order for child in document.children(doi.id)),
                        default=-1,
                    )
                    + 1
                )
                for name in ("q", "t"):
                    definition = definitions.get(name)
                    if definition is None or name in existing:
                        continue
                    document.add_node(
                        parent_id=doi.id,
                        kind="DAI",
                        name=name,
                        sort_order=next_order,
                        attributes={
                            "_templateInherited": True,
                            "sourceType": type_id,
                            "fc": definition.attributes.get("fc", ""),
                            "bType": definition.attributes.get("bType", ""),
                        },
                    )
                    existing.add(name)
                    next_order += 1

    def _load_document(self, project: Iec61850ModelProject) -> ModelDocument:
        cache_key = project.model_checksum or project.model_json or ""
        with self._document_cache_lock:
            cached = self._document_cache.get(project.id)
            if cached and cached[0] == cache_key:
                self._document_cache.move_to_end(project.id)
                return cached[1]
        try:
            document = ModelDocument.from_json(project.id, project.model_json)
        except (TypeError, ValueError, json.JSONDecodeError) as exc:
            raise ValidationError("模型文档损坏或格式不受支持") from exc

        self._normalize_legacy_fcda_names(document)
        self._materialize_inherited_instance_attributes(document)
        with self._document_cache_lock:
            self._document_cache[project.id] = (cache_key, document)
            self._document_cache.move_to_end(project.id)
            while len(self._document_cache) > self._DOCUMENT_CACHE_SIZE:
                self._document_cache.popitem(last=False)
        return document

    def _save_document(self, project: Iec61850ModelProject, document: ModelDocument) -> None:
        content = document.to_json()
        project.model_json = content
        project.model_format_version = document.FORMAT_VERSION
        project.model_node_count = len(document.nodes)
        project.model_checksum = document.checksum(content)
        with self._document_cache_lock:
            self._document_cache[project.id] = (project.model_checksum, document)
            self._document_cache.move_to_end(project.id)
            while len(self._document_cache) > self._DOCUMENT_CACHE_SIZE:
                self._document_cache.popitem(last=False)

