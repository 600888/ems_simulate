    def import_scl(
        self,
        content: bytes,
        *,
        filename: str,
        code: str = "",
        name: str = "",
    ) -> dict[str, Any]:
        try:
            imported = SclModelImporter().parse(content, filename=filename)
        except ValueError as exc:
            raise ValidationError(str(exc)) from exc
        project_data = imported.project
        target_code = (code or project_data["code"]).strip()
        target_name = (name or project_data["name"]).strip()
        if not NAME_PATTERN.fullmatch(target_code):
            raise ValidationError("导入工程编码格式不正确")
        project_id = str(uuid.uuid4())
        with self.session_factory() as session, session.begin():
            if session.scalar(select(Iec61850ModelProject.id).where(Iec61850ModelProject.code == target_code)):
                raise ConflictError(f"工程编码 {target_code} 已存在")
            project = Iec61850ModelProject(
                id=project_id,
                name=target_name,
                code=target_code,
                description=f"从 {filename} 导入",
                file_type=project_data["file_type"],
                standard_version=project_data["standard_version"],
                namespace=project_data["namespace"],
                modeling_mode="IMPORTED",
                status="DRAFT",
            )
            session.add(project)
            document = ModelDocument.empty(project_id)
            for item in imported.nodes:
                document.add_node(
                    node_id=item["id"],
                    parent_id=item["parent_id"],
                    kind=item["kind"],
                    name=item["name"],
                    sort_order=item["sort_order"],
                    attributes=item["attributes"],
                )
            document.rebuild_references()
            self._save_document(project, document)

        return {
            "project": self.get_project(project_id),
            "summary": imported.summary,
            "warnings": imported.warnings,
        }

    def get_project(self, project_id: str) -> dict[str, Any]:
        with self.session_factory() as session:
            project = self._require_project(session, project_id)
            # Keep project metadata reads independent of model size. The tree
            # endpoint already supplies node kinds to the workspace, so parsing
            # a multi-megabyte document here only duplicates startup work.
            return self._project_dict(project)

    def delete_project(self, project_id: str) -> None:
        with self.session_factory() as session, session.begin():
            project = self._require_project(session, project_id)
            session.execute(delete(Iec61850ModelVersion).where(Iec61850ModelVersion.project_id == project_id))
            session.delete(project)
        with self._document_cache_lock:
            self._document_cache.pop(project_id, None)

    def get_tree(
        self,
        project_id: str,
        *,
        compact: bool = False,
        max_depth: int | None = None,
        focus_id: str = "",
        keyword: str = "",
        kind: str = "",
    ) -> list[dict[str, Any]]:
        with self.session_factory() as session:
            project = self._require_project(session, project_id)
            document = self._load_document(project)
            emitted_kind_labels: set[str] = set()
            focus_ancestors: set[str] = set()
            focus_node = document.get(focus_id) if focus_id else None
            while focus_node is not None:
                focus_ancestors.add(focus_node.id)
                focus_node = document.get(focus_node.parent_id) if focus_node.parent_id else None
            normalized_keyword = keyword.strip().lower()
            normalized_kind = kind.strip().upper()
            lnode_type_data_objects = {
                str(node.attributes.get("id") or node.name): {
                    child.name for child in document.children(node.id) if child.kind == "DO_DEF"
                }
                for node in document.nodes
                if node.kind == "LNODE_TYPE"
            }

            def displayed_child_count(
                node: ModelNode,
                children: list[ModelNode],
            ) -> int:
                if node.kind not in {"LN0", "LN"}:
                    return len(children)
                template_names = lnode_type_data_objects.get(
                    str(node.attributes.get("lnType") or ""),
                    set(),
                )
                non_data_count = sum(child.kind != "DOI" for child in children)
                extra_instances = sum(child.kind == "DOI" and child.name not in template_names for child in children)
                return non_data_count + len(template_names) + extra_instances

            filtered_ids: set[str] | None = None
            if normalized_keyword or normalized_kind:
                filtered_ids = set()
                for candidate in document.nodes:
                    matches_keyword = not normalized_keyword or (
                        normalized_keyword in candidate.name.lower() or normalized_keyword in candidate.kind.lower()
                    )
                    matches_kind = not normalized_kind or candidate.kind == normalized_kind
                    if not (matches_keyword and matches_kind):
                        continue
                    current: ModelNode | None = candidate
                    while current is not None and current.id not in filtered_ids:
                        filtered_ids.add(current.id)
                        current = document.get(current.parent_id) if current.parent_id else None

            def build(node: ModelNode, parent_path: str = "", depth: int = 0) -> dict[str, Any]:
                node_children = document.children(node.id)
                effective_child_count = displayed_child_count(
                    node,
                    node_children,
                )
                visible_children = (
                    node_children
                    if filtered_ids is None
                    else [child for child in node_children if child.id in filtered_ids]
                )
                if compact and depth > 1:
                    result = {
                        "id": node.id,
                        "parent_id": node.parent_id,
                        "kind": node.kind,
                        "name": node.name,
                        "child_count": effective_child_count,
                    }
                    if node.kind not in emitted_kind_labels:
                        result["kind_label"] = KIND_LABELS.get(node.kind, node.kind)
                    if node.kind == "EXTENSION" and "lossRisk" in node.attributes:
                        result["attributes"] = {"lossRisk": node.attributes["lossRisk"]}
                    path = ""
                else:
                    result = self._node_dict(
                        node,
                        child_count=effective_child_count,
                    )
                    if compact:
                        result["detail_loaded"] = depth == 0
                    path = f"{parent_path}/{node.name}" if parent_path else node.name
                    if not compact:
                        result["path"] = path
                emitted_kind_labels.add(node.kind)
                should_expand = (
                    filtered_ids is not None or max_depth is None or depth < max_depth or node.id in focus_ancestors
                )
                if should_expand:
                    result["children"] = [build(child, path, depth + 1) for child in visible_children]
                    if len(visible_children) < len(node_children) or effective_child_count != len(node_children):
                        result["children_partial"] = True
                return result

            roots = document.children(None)
            if filtered_ids is not None:
                roots = [root for root in roots if root.id in filtered_ids]
            return [build(root) for root in roots]

    def get_node(
        self,
        project_id: str,
        node_id: str,
        *,
        include_children: bool = False,
    ) -> dict[str, Any]:
        with self.session_factory() as session:
            project = self._require_project(session, project_id)
            document = self._load_document(project)
            node = self._require_node(document, node_id)
            node_children = document.children(node.id)
            child_count = len(node_children)
            if node.kind in {"LN0", "LN"}:
                ln_type_id = str(node.attributes.get("lnType") or "")
                ln_type = next(
                    (
                        candidate
                        for candidate in document.nodes
                        if candidate.kind == "LNODE_TYPE"
                        and str(candidate.attributes.get("id") or candidate.name) == ln_type_id
                    ),
                    None,
                )
                if ln_type is not None:
                    template_names = {child.name for child in document.children(ln_type.id) if child.kind == "DO_DEF"}
                    child_count = (
                        sum(child.kind != "DOI" for child in node_children)
                        + len(template_names)
                        + sum(child.kind == "DOI" and child.name not in template_names for child in node_children)
                    )
            result = self._node_dict(node, child_count=child_count)
            result["schema"] = contextualize_node_schema(document, node, get_kind_schema(node.kind))
            result["path"] = document.node_path(node)
            result["detail_loaded"] = True
            if include_children:
                result["children"] = [
                    {
                        **self._node_dict(
                            child,
                            child_count=len(document.children(child.id)),
                        ),
                        "detail_loaded": False,
                    }
                    for child in document.children(node.id)
                ]
            return result

